import React, { useState } from "react";
import { Plus, X } from "lucide-react";
import { ModalShell, inputCls } from "./ui.jsx";

export function Certificates({ members, onGenerate, onPreview }) {
  return (
    <div>
      <div className="flex justify-between items-center mb-5">
        <h1 className="text-xl font-bold text-emerald-900">Certificate Generator</h1>
        {onGenerate && <button onClick={onGenerate} className="bg-emerald-700 text-white text-sm px-3 py-2 rounded-lg flex items-center gap-1.5"><Plus size={14} /> Generate Certificate</button>}
      </div>
      <p className="text-sm text-stone-500">{onGenerate ? 'Click "Generate Certificate" to create a Participation, Appreciation, Leadership, or Volunteer certificate for any member.' : "Certificates are generated by the officers/leaders."}</p>
    </div>
  );
}

export function CertFormModal({ members, events, onClose, onGenerate }) {
  const [f, setF] = useState({ memberId: members[0]?.id, type: "Participation", eventId: "" });
  return (
    <ModalShell title="Generate Certificate" onClose={onClose}>
      <div className="space-y-3">
        <select className={inputCls} value={f.memberId} onChange={e => setF({ ...f, memberId: e.target.value })}>
          {members.map(m => <option key={m.id} value={m.id}>{m.name}</option>)}
        </select>
        <select className={inputCls} value={f.type} onChange={e => setF({ ...f, type: e.target.value })}>
          {["Participation", "Appreciation", "Leadership", "Volunteer"].map(t => <option key={t}>{t}</option>)}
        </select>
        <button onClick={() => onGenerate({ ...f, member: members.find(m => m.id === f.memberId) })} className="w-full bg-emerald-700 text-white text-sm py-2 rounded-lg">Generate</button>
      </div>
    </ModalShell>
  );
}

